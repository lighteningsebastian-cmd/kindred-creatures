/** A believable print file. PNG magic, so the key gets a .png on it. */
const PNG_BYTES = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

/**
 * A REAL 8x8 PNG, generated by sharp itself so it is genuinely decodable.
 *
 * The drawing half composites what the provider returns THROUGH sharp, so the
 * eight magic bytes above are not enough there: the header alone satisfies
 * metadata() and then fails on the pixels, which is how a plausible-looking
 * hand-written base64 quietly turns a happy-path test into a failure-path one.
 */
const REAL_PNG = new Uint8Array(
  Buffer.from(
    "iVBORw0KGgoAAAANSUhEUgAAAAgAAAAICAYAAADED76LAAAACXBIWXMAAAPoAAAD6AG1e1JrAAAAEklEQVR4nGOoiLL5jw8zjAwFAIMVg0H5dXQZAAAAAElFTkSuQmCC",
    "base64",
  ),
);

/**
 * The canonical bytes for one artwork, made recognisable by its id so a test can
 * assert WHICH portrait was resized, not merely that something was. A Buffer
 * rather than a bare Uint8Array because that is what comes back out of storage,
 * and these are compared against what fulfilment read.
 */
function canonicalBytesFor(artworkId: string): Buffer {
  return Buffer.from([...PNG_BYTES, ...new TextEncoder().encode(artworkId)]);
}

