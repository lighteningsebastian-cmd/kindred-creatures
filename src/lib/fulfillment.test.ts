/**
 * An artwork the way the PRINTING half finds one: drawn after payment, both
 * plates stored, and approved by the customer. Approval is part of the fixture
 * because it is a precondition of printing now, not an afterthought: nothing
 * reaches a press without it (docs/spec-pipeline.md section 5).
 *
 * The canonical bytes are really in storage, because reading them back is the
 * first thing the print step does.
 */
async function readyArtwork(productSlug = "hoodie"): Promise<string> {
  const db = await getDb();
  const id = randomUUID();
  const canonicalKey = `portraits/${id}/1.png`;
  await getStorage().put(canonicalKey, canonicalBytesFor(id), "image/png");
  await db.insert(artworks).values({
    id,
    uploadKey: `uploads/${id}.jpg`,
    style: "watercolor",
    canonicalKey,
    promptVersion: "test",
    previewKey: `previews/${id}/1.png`,
    frontKey: `plates/${id}/front-1.png`,
    backKey: `plates/${id}/back-1.png`,
    approvedAt: new Date(),
    status: "ready",
    productSlug,
  });
  return id;
}

/**
 * An artwork the way CHECKOUT leaves one now: uploaded and styled, with no
 * portrait and no approval. This is what the drawing half actually receives,
 * because generation moved after payment.
 */
async function undrawnArtwork(productSlug = "hoodie"): Promise<string> {
  const db = await getDb();
  const id = randomUUID();
  // The upload has to be real bytes: the drawing step reads it.
  await getStorage().put(`uploads/${id}.jpg`, PNG_BYTES, "image/png");
  await db.insert(artworks).values({
    id,
    uploadKey: `uploads/${id}.jpg`,
    style: "watercolor",
    status: "uploaded",
    productSlug,
    creatureName: "Fenn",
    species: "dog",
    breedId: "one-of-one-dog-large",
  });
  return id;
}

