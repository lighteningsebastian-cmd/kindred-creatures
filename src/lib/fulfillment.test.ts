describe("retryFulfillment", () => {
  it("remakes only the missing line and completes", async () => {
    const { orderId } = await orderWith(["hoodie", "tote"]);
    derivePrintBytesMock
      .mockResolvedValueOnce(PNG_BYTES)
      .mockRejectedValueOnce(new Error("the second one failed"));
    vi.spyOn(console, "error").mockImplementation(() => {});

    expect((await releaseApprovedOrder(orderId)).status).toBe("flagged");
    expect(derivePrintBytesMock).toHaveBeenCalledTimes(2);

    derivePrintBytesMock.mockResolvedValue(PNG_BYTES);
    const retried = await retryFulfillment(orderId);

    expect(retried.status).toBe("sent_to_printer");
    // Three calls, not four: the line that worked the first time keeps the file
    // it already has, and the model is still never asked for anything.
    expect(derivePrintBytesMock).toHaveBeenCalledTimes(3);
    expect(generatePortraitMock).not.toHaveBeenCalled();

    for (const item of await readItems(orderId)) {
      expect(item.printKey).toBeTruthy();
    }
    expect((await readOrder(orderId)).status).toBe("sent_to_printer");
    expect(sendJobSheetMock).toHaveBeenCalledTimes(1);
  });

  it("picks up a paid order whose fulfilment never fired", async () => {
    const { orderId } = await orderWith(["hoodie"]);
    const result = await retryFulfillment(orderId);

    expect(result.status).toBe("sent_to_printer");
    expect(derivePrintBytesMock).toHaveBeenCalledTimes(1);
  });

  it("will not print an order that was flagged without ever being paid", async () => {
    // The one that would cost a garment. The ITN webhook flags an order whose
    // amount did not reconcile, and that order was never paid: it has no
    // payfast_payment_id. Retrying it must not invent one.
    const { orderId } = await orderWith(["hoodie"], "flagged", null);

    const result = await retryFulfillment(orderId);

    expect(result).toMatchObject({
      status: "refused",
      reason: "flagged-without-payment",
    });
    expect(derivePrintBytesMock).not.toHaveBeenCalled();
    expect(generatePortraitMock).not.toHaveBeenCalled();
    expect((await readOrder(orderId)).status).toBe("flagged");
  });

  it("no-ops on an order already at the printer", async () => {
    const { orderId } = await orderWith(["hoodie"], "sent_to_printer");
    expect((await retryFulfillment(orderId)).status).toBe("already-fulfilled");
    expect(sendJobSheetMock).not.toHaveBeenCalled();
  });

  it("refuses a pending order", async () => {
    const { orderId } = await orderWith(["hoodie"], "pending", null);
    expect(await retryFulfillment(orderId)).toMatchObject({
      status: "refused",
      reason: "not-retryable:pending",
    });
    expect(derivePrintBytesMock).not.toHaveBeenCalled();
  });
});

describe("resendJobSheet", () => {
  it("sends the sheet again for an order that already has print files", async () => {
    const { orderId } = await orderWith(["hoodie"]);
    await releaseApprovedOrder(orderId);
    sendJobSheetMock.mockClear();

    const result = await resendJobSheet(orderId);

    expect(result.status).toBe("sent");
    expect(sendJobSheetMock).toHaveBeenCalledTimes(1);
  });

  it("changes nothing: a re-send never rebuilds a print file", async () => {
    const { orderId } = await orderWith(["hoodie"]);
    await releaseApprovedOrder(orderId);
    derivePrintBytesMock.mockClear();

    await resendJobSheet(orderId);

    // The shop is being sent the same links to the same files. A re-send that
    // remade them would hand them a second sheet pointing at different bytes.
    expect(derivePrintBytesMock).not.toHaveBeenCalled();
    expect(generatePortraitMock).not.toHaveBeenCalled();
  });

  it("leaves a breadcrumb, which is the whole reason it lives here", async () => {
    // Every other thing that mails the print shop writes a fulfillment_events
    // row. A re-send that reached past this module would be the one job sheet in
    // the shop's history with no trace, which is the one someone will need.
    const { orderId } = await orderWith(["hoodie"]);
    await releaseApprovedOrder(orderId);

    await resendJobSheet(orderId);

    const events = await eventsFor(orderId);
    const resends = events.filter(
      (event) => event.step === "job-sheet" && event.detail?.startsWith("re-sent"),
    );
    expect(resends).toHaveLength(1);
    expect(resends[0].outcome).toBe("ok");
  });

  it("does not move the order: a re-send is a message about it, not a step in it", async () => {
    const { orderId } = await orderWith(["hoodie"]);
    await releaseApprovedOrder(orderId);
    const db = await getDb();
    await db.update(orders).set({ status: "printed" }).where(eq(orders.id, orderId));

    await resendJobSheet(orderId);

    // An order at printed whose sheet went astray is still printed. Dragging it
    // back to sent_to_printer to explain the re-send would lose that.
    expect((await readOrder(orderId)).status).toBe("printed");
  });

  it("refuses an order with no print files, and sends nothing", async () => {
    // There is nothing to print, so a sheet would send the shop a job it cannot
    // do. The fix for that order is a retry, not a re-send.
    const { orderId } = await orderWith(["hoodie"]);

    const result = await resendJobSheet(orderId);

    expect(result).toMatchObject({ status: "refused", reason: "no-print-files" });
    expect(sendJobSheetMock).not.toHaveBeenCalled();
  });

  it("refuses when only some lines have print files", async () => {
    // A sheet that links three garments and two files is a sheet the shop has to
    // ring us about.
    const { orderId } = await orderWith(["hoodie", "tote"]);
    derivePrintBytesMock
      .mockResolvedValueOnce(PNG_BYTES)
      .mockRejectedValueOnce(new Error("the second one failed"));
    vi.spyOn(console, "error").mockImplementation(() => {});
    await releaseApprovedOrder(orderId);
    sendJobSheetMock.mockClear();

    const result = await resendJobSheet(orderId);

    expect(result).toMatchObject({ status: "refused", reason: "no-print-files" });
    expect(sendJobSheetMock).not.toHaveBeenCalled();
  });

  it("refuses an order that does not exist", async () => {
    await expect(resendJobSheet(randomUUID())).resolves.toMatchObject({
      status: "refused",
      reason: "order-not-found",
    });
  });

  it("reports a failed send loudly, and records it as failed", async () => {
    const { orderId } = await orderWith(["hoodie"]);
    await releaseApprovedOrder(orderId);
    sendJobSheetMock.mockResolvedValue({ ok: false, error: new Error("smtp down") });
    const consoleError = vi.spyOn(console, "error").mockImplementation(() => {});

    const result = await resendJobSheet(orderId);

    expect(result).toMatchObject({ status: "sent" });
    expect(result.status === "sent" && result.jobSheet.ok).toBe(false);
    expect(consoleError).toHaveBeenCalled();

    const events = await eventsFor(orderId);
    expect(
      events.some(
        (event) => event.step === "job-sheet" && event.outcome === "failed",
      ),
    ).toBe(true);
  });
});

describe("fulfillPaidOrder: the drawing half", () => {
  beforeEach(() => {
    // The drawing half composites through sharp, so it needs a real picture.
    generatePortraitMock.mockResolvedValue({
      portraitBytes: REAL_PNG,
      promptVersion: "test",
    });
  });

  it("draws, asks the customer to look, and prints nothing", async () => {
    const { orderId, artworkIds } = await unapprovedOrder(["hoodie"]);
    const result = await fulfillPaidOrder(orderId);

    expect(result.status).toBe("awaiting-approval");
    // Still paid: "paid with unapproved artwork" IS awaiting approval, and the
    // one thing that must not have happened is a job sheet.
    expect((await readOrder(orderId)).status).toBe("paid");
    expect(sendJobSheetMock).not.toHaveBeenCalled();
    expect(derivePrintBytesMock).not.toHaveBeenCalled();
    const [item] = await readItems(orderId);
    expect(item.printKey).toBeNull();

    // Both plates, from one drawing per side.
    const db = await getDb();
    const [artwork] = await db
      .select()
      .from(artworks)
      .where(eq(artworks.id, artworkIds[0]));
    expect(artwork.frontKey).toBeTruthy();
    expect(artwork.backKey).toBeTruthy();
  });

  it("does not redraw an artwork that already has its plates", async () => {
    // A duplicate ITN, a retry or an impatient admin must not pay for a second
    // portrait, still less replace one the customer may have approved already.
    const { orderId } = await orderWith(["hoodie"]);

    await fulfillPaidOrder(orderId);

    expect(generatePortraitMock).not.toHaveBeenCalled();
    const events = await eventsFor(orderId);
    expect(
      events.find((event) => event.step === "draw-artwork")?.outcome,
    ).toBe("skipped");
  });

  it("tells the customer before it flags, when drawing fails", async () => {
    const { orderId } = await unapprovedOrder(["hoodie"]);
    generatePortraitMock.mockRejectedValue(new Error("the model refused"));
    vi.spyOn(console, "warn").mockImplementation(() => {});
    vi.spyOn(console, "error").mockImplementation(() => {});

    const result = await fulfillPaidOrder(orderId);

    expect(result.status).toBe("flagged");
    // A paid order never goes silent. The delay notice goes out BEFORE the flag
    // so a mail failure cannot swallow the only thing they were going to hear.
    const events = await eventsFor(orderId);
    expect(
      events.find((event) => event.step === "draw-artwork")?.outcome,
    ).toBe("failed");
    expect(sendJobSheetMock).not.toHaveBeenCalled();
  });
});

describe("releaseApprovedOrder: the gate in front of the press", () => {
  it("refuses to print artwork nobody has approved", async () => {
    // The whole promise of the shop, in one assertion.
    const { orderId } = await unapprovedOrder(["hoodie"]);

    const result = await releaseApprovedOrder(orderId);

    expect(result).toMatchObject({ status: "refused", reason: "not-approved" });
    expect(sendJobSheetMock).not.toHaveBeenCalled();
    expect(derivePrintBytesMock).not.toHaveBeenCalled();
    expect((await readOrder(orderId)).status).toBe("paid");
  });

  it("refuses when only one artwork of several is approved", async () => {
    // An order with two garments has two portraits. Printing the approved one
    // alongside an unapproved one is exactly the mistake this prevents.
    const { orderId, artworkIds } = await unapprovedOrder(["hoodie", "tote"]);
    const db = await getDb();
    await db
      .update(artworks)
      .set({ approvedAt: new Date() })
      .where(eq(artworks.id, artworkIds[0]));

    const result = await releaseApprovedOrder(orderId);

    expect(result).toMatchObject({ status: "refused", reason: "not-approved" });
    expect(sendJobSheetMock).not.toHaveBeenCalled();
  });

  it("never calls the image provider, however ordinary the order", async () => {
    // The invariant that used to belong to fulfilment as a whole. Printing
    // still never draws: the print file is a resize of the approved bytes, and
    // a second trip to a non-deterministic model would print a portrait nobody
    // agreed to.
    const { orderId } = await orderWith(["hoodie", "tote"]);

    await releaseApprovedOrder(orderId);

    expect(generatePortraitMock).not.toHaveBeenCalled();
  });
});
